'use strict';
const assert=require('assert').strict;
const fs=require('fs');
const vm=require('vm');
const js=fs.readFileSync(__dirname+'/im.js','utf8');
const css=fs.readFileSync(__dirname+'/im.css','utf8');
const store={},root={dataset:{dbxTheme:'light'}};
let systemDark=true;
const context={document:{documentElement:root},window:{matchMedia:()=>({matches:systemDark})},safeStore:()=>({setItem:(key,value)=>store[key]=value})};
vm.createContext(context);
vm.runInContext(js.slice(js.indexOf('function applyTheme('),js.indexOf("  applyTheme(safeStore()")),context);
context.applyTheme('dark');
assert.equal(root.dataset.imTheme,'dark','Plugin theme must have its own attribute');
assert.equal(root.dataset.dbxTheme,'light','Plugin must not share DBX theme state');
context.applyTheme('light');assert.equal(root.dataset.imTheme,'light');
context.applyTheme('system');assert.equal(root.dataset.imTheme,'dark');
systemDark=false;context.applyTheme('system');assert.equal(root.dataset.imTheme,'light');
assert(!/var\(--color-/.test(css),'Plugin colors must be independent of host variables');
assert(!css.includes('[data-dbx-theme=dark]'),'Host theme cannot select plugin colors');
console.log('Theme: explicit light/dark independent of host; system uses OS preference.');
let timerCallback,shown=0,hidden=0;
const body={appendChild(node){node.parentElement=this}},dialog={open:true,appendChild(node){node.parentElement=this}};
const notice={hidden:true,parentElement:body,hidePopover(){hidden++},showPopover(){shown++}};
const toastContext={$:s=>s==='#toast'?notice:dialog,document:{body},toastTimer:undefined,clearTimeout(){},setTimeout(fn){timerCallback=fn;return 1}};
vm.createContext(toastContext);
vm.runInContext(js.slice(js.indexOf('function toast('),js.indexOf('function tokenKey(')),toastContext);
toastContext.toast('已复制');assert.equal(notice.parentElement,dialog,'Toast belongs to active modal, avoiding inert content');assert.equal(shown,1,'Toast must be promoted above modal');
dialog.open=false;toastContext.toast('已保存');assert.equal(notice.parentElement,body);assert.equal(shown,2);
timerCallback();assert.equal(notice.hidden,true);assert(hidden>0);
console.log('Toast: active dialog ownership, top layer, and timeout cleanup passed.');
